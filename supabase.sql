-- FORGE Fitness - esquema do banco Supabase
create table if not exists public.trainings (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);
create table if not exists public.coaches (
  id bigint generated by default as identity primary key,
  name text not null,
  specialty text,
  bio text,
  photo_url text,
  initials text,
  created_at timestamptz not null default now()
);
create table if not exists public.schedules (
  id bigint generated by default as identity primary key,
  day_of_week integer not null check (day_of_week between 0 and 6),
  open_time time,
  close_time time,
  is_closed boolean not null default false
);
create table if not exists public.locations (
  id bigint generated by default as identity primary key,
  name text not null,
  address text,
  phone text,
  email text,
  maps_url text,
  map_embed_url text,
  created_at timestamptz not null default now()
);

alter table public.trainings enable row level security;
alter table public.coaches enable row level security;
alter table public.schedules enable row level security;
alter table public.locations enable row level security;

drop policy if exists "Public can read trainings" on public.trainings;
create policy "Public can read trainings" on public.trainings for select to anon, authenticated using (true);
drop policy if exists "Public can read coaches" on public.coaches;
create policy "Public can read coaches" on public.coaches for select to anon, authenticated using (true);
drop policy if exists "Public can read schedules" on public.schedules;
create policy "Public can read schedules" on public.schedules for select to anon, authenticated using (true);
drop policy if exists "Public can read locations" on public.locations;
create policy "Public can read locations" on public.locations for select to anon, authenticated using (true);

